export function isLegacyErrorText(text: string): boolean {
  if (!text) return false;
  const lower = text.toLowerCase();
  return (
    lower.includes("gemini_api_key") ||
    lower.includes("api key") ||
    lower.includes("apikey") ||
    text.includes("مفتاح جيمناي") ||
    text.includes("مفتاح API") ||
    text.includes("مفتاح api") ||
    text.includes("بحاجه لمفتاح") ||
    text.includes("بحاجة لمفتاح") ||
    text.includes("يرجى ضبط مفتاح") ||
    text.includes("يرجى إعداد مفتاح") ||
    text.includes("المفتاح غير متوفر") ||
    text.includes("انتهت حصة الاستخدام") ||
    text.includes("RESOURCE_EXHAUSTED")
  );
}

